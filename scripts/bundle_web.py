#!/usr/bin/env python3
"""
THERMOPHASE | Web Asset Bundler
Inlines and gzip-compresses web/ assets (index.html, style.css, scaler.js, app.js)
into include/wifi-webpage-gz.h for high-efficiency ESP32 flash storage.
"""

import os
import gzip

def bundle_web():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    web_dir = os.path.join(root_dir, "web")
    output_header = os.path.join(root_dir, "include", "wifi-webpage-gz.h")

    index_html_path = os.path.join(web_dir, "index.html")
    style_css_path = os.path.join(web_dir, "style.css")
    scaler_js_path = os.path.join(web_dir, "scaler.js")
    app_js_path = os.path.join(web_dir, "app.js")

    if not os.path.exists(index_html_path):
        raise FileNotFoundError(f"Missing {index_html_path}")
    if not os.path.exists(style_css_path):
        raise FileNotFoundError(f"Missing {style_css_path}")
    if not os.path.exists(scaler_js_path):
        raise FileNotFoundError(f"Missing {scaler_js_path}")
    if not os.path.exists(app_js_path):
        raise FileNotFoundError(f"Missing {app_js_path}")

    with open(index_html_path, "r", encoding="utf-8") as f:
        html = f.read()

    with open(style_css_path, "r", encoding="utf-8") as f:
        css = f.read()

    with open(scaler_js_path, "r", encoding="utf-8") as f:
        scaler = f.read()

    with open(app_js_path, "r", encoding="utf-8") as f:
        app = f.read()

    # Inline CSS into <style> tag
    html = html.replace('<link rel="stylesheet" href="style.css">', f"<style>\n{css}\n</style>")

    # Inline JS files into separate <script> tags
    html = html.replace('<script src="scaler.js"></script>', f"<script>\n{scaler}\n</script>")
    html = html.replace('<script src="app.js"></script>', f"<script>\n{app}\n</script>")

    raw_bytes = html.encode("utf-8")
    gz_bytes = gzip.compress(raw_bytes, compresslevel=9, mtime=0)

    # Format bytes as a clean C hex array (16 bytes per line)
    hex_lines = []
    chunk_size = 16
    for i in range(0, len(gz_bytes), chunk_size):
        chunk = gz_bytes[i:i + chunk_size]
        hex_lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

    content = f"""#pragma once
#include <Arduino.h>

// ==============================================================================
// THERMOPHASE | Wi-Fi Web Dashboard Compressed Bundle
// Automatically generated by scripts/bundle_web.py from web/ assets
// Raw HTML/CSS/JS Size: {len(raw_bytes):,} bytes | Compressed Gzip Size: {len(gz_bytes):,} bytes
// DO NOT EDIT THIS FILE DIRECTLY - Edit source files under web/ instead
// ==============================================================================

const uint32_t PAGE_INDEX_GZ_LEN = {len(gz_bytes)};
const uint8_t PAGE_INDEX_GZ[] PROGMEM = {{
{chr(10).join(hex_lines)}
}};
"""

    os.makedirs(os.path.dirname(output_header), exist_ok=True)
    with open(output_header, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"[bundle_web] Successfully bundled web/ assets into {output_header}")
    print(f"[bundle_web] Uncompressed: {len(raw_bytes):,} bytes -> Gzipped: {len(gz_bytes):,} bytes ({(len(gz_bytes)/len(raw_bytes))*100:.1f}%)")

if __name__ == "__main__":
    bundle_web()

